const baseNow = Date.UTC(2026, 10, 5, 12);
const matches = code => error => error.code === code && error.message === code;
const settles = results => results.filter(result => result.status === 'fulfilled');
const rejects = results => results.filter(result => result.status === 'rejected');
let cluster, clusterUnavailable;

async function port() {
  const server = createServer();
  await new Promise((resolve, reject) => server.listen(0, '127.0.0.1', resolve).once('error', reject));
  const value = server.address().port;
  await new Promise(resolve => server.close(resolve));
  return value;
}
async function temporaryPostgres() {
  let bin;
  try { bin = execFileSync('pg_config', ['--bindir'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim(); }
  catch { return null; }
  if (!['initdb', 'pg_ctl'].every(name => existsSync(path.join(bin, name))) || process.getuid?.() === 0) return null;
  const root = await mkdtemp('/tmp/floww-mandates-pg-'), data = path.join(root, 'data'), socket = path.join(root, 'socket');
  const selectedPort = await port(), control = path.join(bin, 'pg_ctl');
  await mkdir(socket, { mode: 0o700 });
  let started = false;
  const stop = async () => {
    if (started) {
      await exec(control, ['-D', data, '-m', 'fast', '-w', 'stop'], { timeout: 20_000 });
      started = false;
    }
    // This path was generated by mkdtemp in this test only. No live resource or
    // application database is read or removed by the test harness.
    await rm(root, { recursive: true, force: true });
  };
  try {
    await exec(path.join(bin, 'initdb'), ['-D', data, '--no-locale', '--encoding=UTF8', '--auth-local=trust',
      '--auth-host=trust', '--username=floww_budget_test'], { timeout: 20_000 });
    await exec(control, ['-D', data, '-l', path.join(root, 'server.log'), '-w', '-o',
      `-h 127.0.0.1 -p ${selectedPort} -k ${socket} -c shared_buffers=16MB -c max_connections=15 -c max_wal_size=32MB`,
      'start'], { timeout: 20_000 });
    started = true;
    return { root, url: `postgresql://floww_budget_test@127.0.0.1:${selectedPort}/postgres`, stop };
  } catch {
    await stop();
    throw new Error('TEMPORARY_POSTGRES_SETUP_FAILED');
  }
}
